#!/usr/bin/env python3
"""Sync public YouTube channel data into js/youtube-data.js for the site.

No key needed: reads the channel's public RSS feed (latest 15 uploads).
With YOUTUBE_API_KEY set (repo secret), it also pulls the full upload list,
view counts, durations and subscriber count from the YouTube Data API.

Only rewrites the file when the data actually changed, so the scheduled
workflow doesn't commit when nothing happened.
"""
import json, os, re, sys, urllib.error, urllib.parse, urllib.request
import xml.etree.ElementTree as ET
from datetime import datetime, timezone

CHANNEL_ID = os.environ.get("YOUTUBE_CHANNEL_ID", "UCiIQgFerfIQ8my1xAd28ZEA")
KEY = os.environ.get("YOUTUBE_API_KEY", "").strip()
OUT = os.path.join(os.path.dirname(__file__), "..", "js", "youtube-data.js")
PREFIX = "/* Generated by scripts/sync_youtube.py (GitHub Action \"YouTube sync\"). Don't edit by hand. */\nwindow.YT_SYNC = "
SHORT_MAX_SECONDS = 180  # YouTube Shorts can be up to 3 minutes


def get(url, method="GET"):
    req = urllib.request.Request(url, method=method, headers={"User-Agent": "portfolio-youtube-sync"})
    return urllib.request.urlopen(req, timeout=30)


def api(path, **params):
    params["key"] = KEY
    with get(f"https://www.googleapis.com/youtube/v3/{path}?{urllib.parse.urlencode(params)}") as r:
        return json.load(r)


def iso_seconds(d):
    m = re.fullmatch(r"P(?:(\d+)D)?T?(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?", d or "")
    if not m:
        return None
    dd, h, mi, s = (int(x or 0) for x in m.groups())
    return dd * 86400 + h * 3600 + mi * 60 + s


def clock(sec):
    if sec is None:
        return ""
    h, rem = divmod(sec, 3600)
    m, s = divmod(rem, 60)
    return f"{h}:{m:02d}:{s:02d}" if h else f"{m}:{s:02d}"


class _NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *a, **k):
        return None


def is_short_by_url(vid):
    """/shorts/<id> answers 200 for a Short and redirects for a normal video."""
    opener = urllib.request.build_opener(_NoRedirect)
    try:
        r = opener.open(urllib.request.Request(f"https://www.youtube.com/shorts/{vid}", method="HEAD",
                                               headers={"User-Agent": "Mozilla/5.0"}), timeout=15)
        return r.status == 200
    except Exception:
        return False


def from_rss():
    ns = {"a": "http://www.w3.org/2005/Atom", "yt": "http://www.youtube.com/xml/schemas/2015",
          "media": "http://search.yahoo.com/mrss/"}
    with get(f"https://www.youtube.com/feeds/videos.xml?channel_id={CHANNEL_ID}") as r:
        root = ET.fromstring(r.read())
    channel = {"title": root.findtext("a:title", "", ns), "subscribers": None, "video_count": None}
    videos = []
    for e in root.findall("a:entry", ns):
        vid = e.findtext("yt:videoId", "", ns)
        stats = e.find("media:group/media:community/media:statistics", ns)
        videos.append({
            "id": vid,
            "title": e.findtext("a:title", "", ns),
            "published": e.findtext("a:published", "", ns),
            "views": int(stats.get("views")) if stats is not None and stats.get("views") else None,
            "duration": "",
            "short": is_short_by_url(vid),
        })
    return channel, videos


def from_api():
    ch = api("channels", part="snippet,statistics,contentDetails", id=CHANNEL_ID)["items"][0]
    st = ch["statistics"]
    channel = {
        "title": ch["snippet"]["title"],
        "subscribers": None if st.get("hiddenSubscriberCount") else int(st.get("subscriberCount", 0)),
        "video_count": int(st.get("videoCount", 0)),
    }
    uploads, ids, token = ch["contentDetails"]["relatedPlaylists"]["uploads"], [], None
    while len(ids) < 200:
        try:
            page = api("playlistItems", part="contentDetails", playlistId=uploads, maxResults=50,
                       **({"pageToken": token} if token else {}))
        except urllib.error.HTTPError as e:
            if e.code == 404 and not ids:  # the uploads playlist doesn't exist until the first public video
                break
            raise
        ids += [i["contentDetails"]["videoId"] for i in page.get("items", [])]
        token = page.get("nextPageToken")
        if not token:
            break
    videos = []
    for i in range(0, len(ids), 50):
        for v in api("videos", part="snippet,contentDetails,statistics,status", id=",".join(ids[i:i + 50]))["items"]:
            if v["status"].get("privacyStatus") != "public":
                continue
            sec = iso_seconds(v["contentDetails"].get("duration"))
            videos.append({
                "id": v["id"],
                "title": v["snippet"]["title"],
                "published": v["snippet"]["publishedAt"],
                "views": int(v["statistics"]["viewCount"]) if "viewCount" in v["statistics"] else None,
                "duration": clock(sec),
                "short": sec is not None and sec <= SHORT_MAX_SECONDS and is_short_by_url(v["id"]),
            })
    return channel, videos


def main():
    try:
        channel, videos = from_api() if KEY else from_rss()
    except Exception as e:  # never wipe good data because YouTube hiccuped
        print(f"sync failed, keeping existing data: {e}", file=sys.stderr)
        sys.exit(1)
    videos.sort(key=lambda v: v["published"], reverse=True)
    data = {"channel_id": CHANNEL_ID, "source": "api" if KEY else "rss", "channel": channel, "videos": videos}

    old = None
    if os.path.exists(OUT):
        txt = open(OUT, encoding="utf-8").read()
        if txt.startswith(PREFIX):
            try:
                old = json.loads(txt[len(PREFIX):].rstrip().rstrip(";"))
            except ValueError:
                old = None
            if isinstance(old, dict):
                old.pop("synced_at", None)
    if old == data:
        print(f"no change ({len(videos)} videos)")
        return
    data["synced_at"] = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(PREFIX + json.dumps(data, indent=2, ensure_ascii=False) + ";\n")
    print(f"updated: {len(videos)} videos ({data['source']})")


if __name__ == "__main__":
    main()
